const catalogues: Record<LanguageCode, TranslationCatalogue> = {
  'en-GB': enGB,
  'en-US': enUS,
  'fr-FR': frFR
};

export function normaliseLanguage(language?: string): LanguageCode {
  return language === 'en-US' || language === 'fr-FR' ? language : 'en-GB';
}

export function createTranslator(language?: string) {
  const catalogue = catalogues[normaliseLanguage(language)];

  return function _t(key: TranslationKey, values: TranslationValues = {}) {
    const template = catalogue[key] ?? enGB[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, valueKey: string) =>
      values[valueKey] === undefined ? match : String(values[valueKey])
    );
  };
}
